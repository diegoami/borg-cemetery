import json
from pathlib import Path
import re
import sys
import tempfile
import unittest

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / 'scripts'))
from death_pages import dossier_page, episode_page


class DeathPagesTest(unittest.TestCase):
    def test_historical_page_retains_originals_and_zero_seed(self):
        with tempfile.TemporaryDirectory() as tmp:
            case = Path(tmp)
            original = dict(id='D0001', character='Human Warrior', raw_cause='a monster',
                            identity=dict(seed=0, source='a' * 40, turn=123))
            (case / 'record.json').write_text(json.dumps(original))
            (case / 'report.md').write_text('Original assessment.\n')
            before = {name: (case / name).read_bytes() for name in ('record.json', 'report.md')}
            self.assertTrue(dossier_page(case))
            landing = (case / 'README.md').read_text()
            self.assertIn('**Seed: `0`**', landing)
            self.assertIn('[Read the original death report](report.md)', landing)
            self.assertIn('not retained', landing)
            self.assertNotIn('](media/episode.gif)', landing)
            for name, value in before.items():
                self.assertEqual((case / name).read_bytes(), value)
            (case / 'README.md').write_text('Human-written landing page.\n')
            self.assertFalse(dossier_page(case))
            self.assertEqual((case / 'README.md').read_text(), 'Human-written landing page.\n')

    def test_saved_scenario_page_exposes_assets_without_reseeding_claim(self):
        with tempfile.TemporaryDirectory() as tmp:
            case = Path(tmp)
            (case / 'media').mkdir()
            for name in ('report.md', 'inventory.md', 'sequence.json', 'start.save.gz', 'media/episode.gif'):
                (case / name).write_bytes(b'fixture')
            (case / 'media/media.json').write_text(json.dumps(dict(status='partial')))
            (case / 'scenario.json').write_text(json.dumps(dict(status='ready_for_restart_trials',
                birth_seed=123, start_turn=50, origin=dict(program='borg-rs', source_commit='a' * 40))))
            event = dict(kind='death', turn=100, start=dict(turn=60), cause='a monster')
            episode_page(case, event, dict(seed=123))
            landing = (case / 'README.md').read_text()
            for target in ('media/episode.gif', 'inventory.md', 'start.save.gz', 'scenario.json'):
                self.assertIn(f']({target})', landing)
            self.assertIn('partial', landing)
            self.assertIn('does not reseed', landing)

    def test_existing_deaths_have_landing_pages_with_valid_local_links(self):
        root = Path(__file__).resolve().parents[1]
        for path in (root / 'deaths').glob('D*/record.json'):
            self.assertTrue((path.parent / 'README.md').is_file(), str(path))
        for path in (root / 'runs').rglob('scenario.json'):
            scenario = json.loads(path.read_text())
            if scenario.get('event_kind') == 'death':
                self.assertTrue((path.parent / 'README.md').is_file(), str(path))
        for tree in ('deaths', 'runs'):
            for page in (root / tree).rglob('README.md'):
                content = page.read_text()
                if '<!-- generated by scripts/death_pages.py -->' not in content:
                    continue
                for target in re.findall(r'\]\(([^)]+)\)', content):
                    if not target.startswith(('https://', 'http://', '#')):
                        self.assertTrue((page.parent / target).exists(), f'{page}: {target}')


if __name__ == '__main__':
    unittest.main()
