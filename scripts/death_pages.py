#!/usr/bin/env python3
"""Generate GitHub-rendered landing pages beside immutable death evidence."""
import argparse
import json
from pathlib import Path
import re

MARKER = '<!-- generated by scripts/death_pages.py -->'


def read(path):
    try:
        value = json.loads(path.read_text())
        return value if isinstance(value, dict) else {}
    except (OSError, ValueError):
        return {}


def text(value):
    return str(value).replace('|', '\\|').replace('\n', ' ')


def first(*values):
    return next((v for v in values if v is not None), 'Not recorded')


def save_page(directory, content):
    path = directory / 'README.md'
    if path.exists() and MARKER not in path.read_text():
        return False  # Preserve human-written entry points.
    path.write_text(MARKER + '\n\n' + '\n'.join(content) + '\n')
    return True


def source_link(program, source):
    if program in ('borg-rs', 'borg-reborn-rs') and re.fullmatch(r'[0-9a-f]{7,40}', str(source)):
        return f'[{source}](https://github.com/diegoami/{program}/commit/{source})'
    return text(source)


def links(directory, choices):
    return [f'- [{label}]({name})' for name, label in choices if (directory / name).exists()]


def episode_page(directory, event, identity):
    scenario = read(directory / 'scenario.json')
    origin = scenario.get('origin', {})
    seed = first(identity.get('seed'), scenario.get('birth_seed'))
    kind = event.get('kind', scenario.get('event_kind', 'episode'))
    heading = 'Death' if kind == 'death' else 'Near-death candidate'
    source = first(identity.get('source_commit'), origin.get('source_commit'))
    program = first(identity.get('program'), origin.get('program'))
    terminal = identity.get('summary', {})
    content = [f'# {heading} · seed {seed}', '',
               f"**Seed: `{seed}`** · {text(program)}", '',
               '| Detail | Value |', '| --- | --- |',
               f"| Outcome | {text(event.get('resolution', kind))} |",
               f"| Cause | {text(event.get('cause', terminal.get('death_cause', 'Not recorded')) if kind == 'death' else 'Risk episode; no death at this endpoint')} |",
               f"| Character | {text(terminal.get('race', 'Race index ' + str(identity.get('race_idx', 'unknown'))))} "
               f"{text(terminal.get('class', 'class index ' + str(identity.get('class_idx', 'unknown'))))} |",
               f"| Episode boundary | {text((event.get('start') or {}).get('turn', scenario.get('report_start_turn', 'Not recorded')))} |",
               f"| Endpoint turn | {text(event.get('turn', scenario.get('original_endpoint_turn', 'Not recorded')))} |",
               f'| Program version | {source_link(program, source)} |', '',
               '[Read the chronological report](report.md)', '']
    gif = directory / 'media/episode.gif'
    media = read(directory / 'media/media.json')
    if gif.is_file():
        content += ['## Watch the episode', '', '![Episode animation](media/episode.gif)', '',
                    '[Open GIF](media/episode.gif) · [Screenshot provenance](media/media.json)', '',
                    f"Capture: {text(media.get('status', 'not recorded'))}. Screens are sampled; side panels show the last available observations.", '']
    else:
        content += ['Animation: not retained for this episode.', '']
    content += ['## Inventory and decisions', '']
    content += links(directory, [('inventory.md', 'Inventory, equipment and spells'),
                                 ('inventory.json', 'Inventory observations'),
                                 ('sequence.json', 'State, message and Borg-decision chronology')])
    if not (directory / 'inventory.md').exists():
        content += ['Inventory: not retained for this episode.']
    content += ['', '## Try another Borg', '',
                f"Scenario: **{text(scenario.get('status', 'not recorded'))}**.", '']
    if (directory / 'start.save.gz').is_file():
        content += ['[Download starting save](start.save.gz) · [Scenario manifest](scenario.json)', '',
                    f"Saved turn: {scenario.get('start_turn')}. Both versions start with fresh Borg memory and the saved engine RNG. "
                    'The displayed seed identifies the original birth; it does not reseed a loaded scenario.', '',
                    '[Run a scenario comparison](https://github.com/diegoami/borg-cemetery/actions/workflows/try-scenario.yml). '
                    'Select the cemetery branch/commit containing this directory, paste its repository-relative path as the scenario, '
                    'and choose the alternative Borg project/version.', '']
    else:
        content += ['No runnable starting save was retained. The report remains available.', '']
    content += ['## Evidence and navigation', '']
    content += links(directory, [('scenario.json', 'Identity, save hashes and startup contract'),
                                 ('media/', 'Terminal captures'), ('baseline-profile.txt', 'Original custom profile')])
    content += ['', '[All episodes from this run](../README.md)', '',
                'This episode belongs to its original birth. Replays and overlapping episodes are not additional independent lives.']
    return save_page(directory, content)


def analysis_page(directory):
    result = read(directory / 'scenarios.json')
    identity = result.get('identity', {})
    content = [f"# Episodes · seed {identity.get('seed', 'not recorded')}", '',
               'Each entry opens a landing page with the available report, inventory, animation and saved scenario.', '',
               '| Episode | Outcome | Endpoint |', '| --- | --- | --- |']
    for event in result.get('events', []):
        name = event.get('id')
        if name and (directory / name / 'README.md').is_file():
            content.append(f"| [{text(name)}]({name}/README.md) | {text(event.get('kind'))} | {event.get('turn', 'Not recorded')} |")
    content += ['', '[Analysis overview](analysis.md) · [Machine-readable episode index](scenarios.json)']
    return save_page(directory, content)


def dossier_page(directory):
    record = read(directory / 'record.json')
    identity = record.get('identity', {})
    summary = read(directory / 'summary.json')
    source = first(identity.get('source'), identity.get('git_rev'))
    program = 'borg-reborn-rs' if str(record.get('schema', '')).startswith('borg-reborn-rs/') else 'borg-rs'
    seed = identity.get('seed')
    terminal = record.get('terminal', {})
    content = [f"# {record.get('id', directory.name)} · {text(record.get('character', 'Borg death'))}", '',
               f"**Seed: `{seed}`**" if seed is not None else '**Effective seed: not recorded or saved engine RNG.**', '',
               '| Detail | Value |', '| --- | --- |',
               f"| Cause | {text(first(record.get('raw_cause'), summary.get('death_cause')))} |",
               f"| Death turn | {first(identity.get('turn'), terminal.get('turn'), summary.get('game_turns'))} |",
               f'| Program version | {source_link(program, source)} |', '',
               '[Read the original death report](report.md)', '', '## Available evidence', '']
    content += links(directory, [('inventory.json', 'Inventory'), ('assessment.json', 'Assessment and proposed actions'),
                                 ('record.json', 'Original death record and identity'), ('summary.json', 'Terminal summary'),
                                 ('build.json', 'Build and executable hashes'), ('config.txt', 'Run configuration'),
                                 ('params.json', 'Borg parameters'), ('trace-tail.jsonl', 'Final Borg decisions'),
                                 ('analysis-evidence.json', 'Analysis evidence'), ('analysis-anchors/', 'Recorded observations'),
                                 ('native/', 'Native evidence'), ('CharOutput.txt', 'Character output')])
    content += ['', 'Animation and runnable scenario: not retained in this original dossier. '
                'New CI episodes link these when available.', '',
                'Original reports and evidence are preserved as written. The case identifier is scoped to its registry; '
                'repeated attempts are not independent deaths.', '', '[Parent record or registry](../README.md)']
    return save_page(directory, content)


def run_page(directory):
    record = read(directory / 'run.json')
    summary = record.get('summary', {})
    content = [f"# {text(record.get('status', 'run'))} · seed {record.get('seed', 'not recorded')}", '',
               f"**Seed: `{record.get('seed', 'not recorded')}`** · {text(record.get('program', 'Borg'))}", '',
               f"Cause: {text(summary.get('death_cause') or 'not applicable / not recorded')}. "
               f"Endpoint turn: {summary.get('game_turns', 'not recorded')}.", '',
               'Program version: ' + source_link(record.get('program'), record.get('source_commit')), '']
    content += links(directory, [('analysis/README.md', 'Open episode landing pages, inventory, GIFs and saved scenarios'),
                                 ('death-report.md', 'Original death report'), ('run.json', 'Seed, version and run receipt'),
                                 ('summary.json', 'Terminal summary'), ('process.json', 'Process result'),
                                 ('config.txt', 'Run configuration'), ('params.json', 'Borg parameters')])
    return save_page(directory, content)


def generate(root):
    count = 0
    for tree in ('deaths', 'runs'):
        for path in sorted((root / tree).rglob('record.json')):
            count += dossier_page(path.parent)
    for path in sorted((root / 'runs').rglob('scenarios.json')):
        result = read(path)
        for event in result.get('events', []):
            name = event.get('id')
            if name and Path(name).name == name and (path.parent / name / 'report.md').is_file():
                count += episode_page(path.parent / name, event, result.get('identity', {}))
        if any(path.parent.glob('event-*/README.md')):
            count += analysis_page(path.parent)
    for path in sorted((root / 'runs').rglob('run.json')):
        count += run_page(path.parent)
    return count


if __name__ == '__main__':
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('root', nargs='?', default=Path('.'), type=Path)
    args = p.parse_args()
    print(f'Wrote {generate(args.root)} landing pages')
